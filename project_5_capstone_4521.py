def collate_pil(batch):
    images, labels = zip(*batch)
    return list(images), torch.tensor(labels, dtype=torch.long)


def extract_embeddings(dataset_obj, split_name):
    cache_x = Path(cache_dir) / f"{split_name}_embeddings.pt"
    cache_y = Path(cache_dir) / f"{split_name}_labels.pt"

    if cache_x.exists() and cache_y.exists():
        print(f"Loading cached embeddings for {split_name}")
        return torch.load(cache_x, map_location="cpu"), torch.load(cache_y, map_location="cpu")

    loader = DataLoader(
        dataset_obj,
        batch_size=embed_batch,
        shuffle=False,
        num_workers=0,
        collate_fn=collate_pil,
    )

    all_embs = []
    all_labs = []

    print(f"Extracting embeddings for {split_name} in batches of {embed_batch} ...")
    with torch.no_grad():
        for images, labels in tqdm(loader, desc=f"Embeddings [{split_name}]"):
            # Convert image batch into model inputs and move tensors to selected device.
            inputs = dino_processor(images=images, return_tensors="pt").to(DEVICE)

            outputs = dino_model(**inputs)

            # Use [CLS] token embedding as the global image representation.
            embs = outputs.last_hidden_state[:, 0, :].cpu()
            all_embs.append(embs)
            all_labs.append(labels)

    X = torch.cat(all_embs, dim=0)
    y = torch.cat(all_labs, dim=0)
    torch.save(X, cache_x)
    torch.save(y, cache_y)
    print(f"Saved {split_name} embeddings: {tuple(X.shape)}")
    return X, y

