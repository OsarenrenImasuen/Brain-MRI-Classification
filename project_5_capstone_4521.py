def top_confusion_pairs(cm, names, k=5):
    pairs = []
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            if i != j and cm[i, j] > 0:
                pairs.append((cm[i, j], i, j))
    pairs.sort(reverse=True)
    return [(count, names[i], names[j]) for count, i, j in pairs[:k]]


