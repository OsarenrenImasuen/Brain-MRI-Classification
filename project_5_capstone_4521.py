epoch_iter = tqdm(range(1, mlp_epoch + 1), desc="MLP epochs", unit="epoch")
for epoch in epoch_iter:
    mlp.train()
    train_loss = 0.0

    for xb, yb in train_loader:
        xb, yb = xb.to(DEVICE), yb.to(DEVICE)
        optimizer.zero_grad()
        logits = mlp(xb)
        loss = criterion(logits, yb)
        loss.backward()
        optimizer.step()
        train_loss += loss.item() * xb.size(0)

    train_loss /= len(train_loader.dataset)

    mlp.eval()
    val_loss = 0.0
    val_preds = []
    val_true = []

    with torch.no_grad():
        for xb, yb in val_loader:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            logits = mlp(xb)
            loss = criterion(logits, yb)
            val_loss += loss.item() * xb.size(0)
            val_preds.append(logits.argmax(dim=1).cpu().numpy())
            val_true.append(yb.cpu().numpy())

    val_loss /= len(val_loader.dataset)
    val_preds = np.concatenate(val_preds)
    val_true = np.concatenate(val_true)
    val_acc = accuracy_score(val_true, val_preds)

    history["train_loss"].append(train_loss)
    history["val_loss"].append(val_loss)
    history["val_acc"].append(val_acc)

    improved = val_acc > best_val_acc
    if improved:
        best_val_acc = val_acc
        torch.save(mlp.state_dict(), best_path)
        patience_left = 6
    else:
        patience_left -= 1

    epoch_iter.set_postfix(
        train_loss=f"{train_loss:.4f}",
        val_loss=f"{val_loss:.4f}",
        val_acc=f"{val_acc:.4f}",
        best=f"{best_val_acc:.4f}",
        patience=patience_left,
    )

    # Stop when validation accuracy no longer improves for several epochs
    if patience_left == 0:
        print("Early stopping triggered.")
        break

